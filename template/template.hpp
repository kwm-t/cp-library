//  Library Template (Instruction-Based)
// ============================================
//
// このファイルは「新しいライブラリを作るためのテンプレ」です。
// 使用時は必ず以下のルールに従って書き換えてください。
//
// --------------------------------------------
// ■ 0. コーディングルール（厳守）
// --------------------------------------------
// - #include <bits/stdc++.h> は使用禁止
// - using namespace std; は使用禁止
// - 必要なヘッダのみ個別に include すること
// - std:: を明示して使用すること
//
// --------------------------------------------
// ■ 1. include guard を変更
// --------------------------------------------
// 形式:
//   KWM_T_<PATH>_<FILENAME>_HPP
//
// ルール:
//   - ディレクトリ構造 + ファイル名から生成
//   - すべて大文字
//   - '/' や '.' は '_' に変換
//
// 例:
//   tree/centroid.hpp
//     → KWM_T_TREE_CENTROID_HPP
//
// --------------------------------------------
// ■ 2. namespace を変更
// --------------------------------------------
// 形式:
//   namespace kwm_t::<path>
//
// ルール:
//   - ディレクトリ構造に対応させる
//
// 例:
//   tree/centroid.hpp
//     → namespace kwm_t::tree
//
// --------------------------------------------
// ■ 3. class / 関数名を適切に変更
// --------------------------------------------
// - TemplateClass などのダミー名は必ず削除
// - 実装内容に応じた名前に変更
//
// --------------------------------------------
// ■ 4. Doxygen コメントを必ず付与・更新
// --------------------------------------------
// - 新しいライブラリを作成するときは、ファイル先頭に
//   以下の Doxygen コメントを必ず付与すること。
//
//   /**
//    * @file <FILENAME>
//    * @brief <ライブラリの概要>
//    * @author kwm_t
//    * @see <公開したライブラリのURL>
//    */
//
// - @file:
//   ファイル名を記載する。
// - @brief:
//   ライブラリの概要を記載する。ファイル名などから推測できる範囲で
//   仮置きしてもよいが、完成時に内容を確認・修正すること。
// - @author:
//   必ず kwm_t と記載する。
// - @see:
//   GitHub などに公開したライブラリ自身の URL を記載する。
//   ファイルのパスやリポジトリ名を変更した場合は URL も更新すること。
//   未公開・未 verified の場合も項目を削除せず、状態を明記すること。
//
// - クラスや関数の説明には、必要に応じて別途 Doxygen コメントを付与する。
// - このテンプレート説明は完成後に削除してよいが、
//   ファイル先頭の Doxygen コメントは削除しないこと。
//
// --------------------------------------------
// ■ 5. 実装内容に応じた説明を記載
// --------------------------------------------
// - 典型用途、計算量、テンプレート引数、引数、制約・注意点、使用例を記載する。
// - verified の項目には、動作確認に使用した提出先 URL を記載する。
// - 未 verified の場合は、その旨を明記する。
//
// ============================================

