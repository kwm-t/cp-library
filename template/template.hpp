//
// --------------------------------------------
// ■ 2. namespace を変更
// --------------------------------------------
// 形式:
//   namespace kwm_t::<path>
//
// ルール:
//   - ディレクトリ構造に対応させる
//
// 例:
//   tree/centroid.hpp
//     → namespace kwm_t::tree
//
// --------------------------------------------
// ■ 3. class / 関数名を適切に変更
// --------------------------------------------
// - TemplateClass などのダミー名は必ず削除
// - 実装内容に応じた名前に変更
//
// --------------------------------------------
